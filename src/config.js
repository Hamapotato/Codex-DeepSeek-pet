'use strict';

/**
 * One place for every path the bridge needs.
 *
 * hook.js, the watchdog, the launcher and the patcher all read these, so moving
 * the harness (or the dsh-pet package) only takes a single edit. All overrides
 * are environment variables so the same files keep working on another machine.
 */

const path = require('path');
const os = require('os');
const fs = require('fs');

/** Repository root (the directory that holds README.md and the entry shims). */
const PROJECT_DIR = path.resolve(__dirname, '..');

/**
 * DeepSeek Harness 的安装目录。仓库里不写死任何人的绝对路径，按这个顺序找：
 *   1. 环境变量 DSH_HOME
 *   2. 用户主目录下的 `.dsh-home` 文件（一行路径，本机覆盖用，不进仓库）
 *   3. ~/DeepSeekHarness（通用默认）
 */
function resolveDshHome() {
  if (process.env.DSH_HOME) return process.env.DSH_HOME;
  try {
    const override = fs.readFileSync(path.join(os.homedir(), '.dsh-home'), 'utf8').trim();
    if (override) return override;
  } catch {}
  return path.join(os.homedir(), 'DeepSeekHarness');
}

const DSH_HOME = resolveDshHome();

/** The installed dsh-pet package (its files are never edited by hand). */
const PKG = path.join(DSH_HOME, 'profiles', 'desktop', 'node_modules', 'dsh-pet');

/** Per-user runtime state: logs, caches, the generated launch VBS. */
const STATE_DIR = path.join(process.env.LOCALAPPDATA || os.tmpdir(), 'dsh-pet-codex');

/** Written by the standalone host; authoritative for its port and token. */
const STANDALONE_RUNTIME = path.join(DSH_HOME, 'dsh-pet', 'standalone-runtime.json');

/** Stock standalone bundle (never patched). */
const STOCK_JS = path.join(PKG, 'lib', 'standalone.js');

/** Patched standalone bundle generated by src/build-patches.js. */
const PATCHED_JS = path.join(PKG, 'lib', 'standalone-codex.js');

/** Bundle to run: the patched one unless overridden. */
const STANDALONE_JS = process.env.DSH_PET_STANDALONE_JS || PATCHED_JS;

/** Launcher that rebuilds patches and starts the bundle above. */
const STANDALONE_START =
  process.env.DSH_PET_STANDALONE_START || path.join(__dirname, 'standalone-launcher.js');

/** Local HTTP API of the standalone host. */
const STANDALONE_PORT = Number(process.env.DSH_PET_PORT || 3080);
const ROUTE = '/dsh-pet-7340';

/** Shared launch throttle (hook + watchdog must not double-launch). */
const LAUNCH_FILE = path.join(STATE_DIR, 'host-launch.json');

/** Generated hidden VBScript that starts the launcher through Explorer. */
const LAUNCH_VBS = path.join(STATE_DIR, 'launch-standalone.vbs');

const PORT_CACHE = path.join(STATE_DIR, 'port.json');
const THROTTLE_FILE = path.join(STATE_DIR, 'throttle.json');
const DEBUG_LOG = path.join(STATE_DIR, 'debug.log');
const LOG = path.join(STATE_DIR, 'watch.log');

/** Python-free way to reach the interpreter that is already running us. */
const NODE_EXE = process.execPath;

/** Codex transcript root: <CODEX_HOME>/sessions/YYYY/MM/DD/rollout-*.jsonl */
const CODEX_HOME = process.env.CODEX_HOME || path.join(os.homedir(), '.codex');
const CODEX_SESSIONS = path.join(CODEX_HOME, 'sessions');

/** Pet diary: one Markdown file per day plus a small state cache. */
const DIARY_DIR = process.env.DSH_PET_DIARY_DIR || path.join(DSH_HOME, 'dsh-pet', 'diary');

module.exports = {
  PROJECT_DIR,
  DSH_HOME,
  PKG,
  STATE_DIR,
  STANDALONE_RUNTIME,
  STOCK_JS,
  PATCHED_JS,
  STANDALONE_JS,
  STANDALONE_START,
  STANDALONE_PORT,
  ROUTE,
  LAUNCH_FILE,
  LAUNCH_VBS,
  PORT_CACHE,
  THROTTLE_FILE,
  DEBUG_LOG,
  LOG,
  NODE_EXE,
  CODEX_HOME,
  CODEX_SESSIONS,
  DIARY_DIR,
};
